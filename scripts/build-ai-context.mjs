import { readFile, readdir, writeFile } from 'node:fs/promises';
import { posix, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const root = fileURLToPath(new URL('../', import.meta.url));
export const rawBase = 'https://raw.githubusercontent.com/forgesworn/relayswarm/main/';

export async function documentationSources() {
  const preferred = ['README.md', 'GETTING-STARTED.md', 'API.md', 'STATUS.md',
    'FIELD-TEST.md', 'NATIVE-TRANSPORT.md', 'THREAT-MODEL.md', 'FAQ.md',
    'LANDSCAPE.md', 'MAINTAINING-DOCS.md'];
  const guides = (await readdir(resolve(root, 'docs'))).filter(name => name.endsWith('.md'));
  guides.sort((a, b) => {
    const rank = name => preferred.includes(name) ? preferred.indexOf(name) : preferred.length;
    return rank(a) - rank(b) || a.localeCompare(b, 'en');
  });
  return ['README.md', 'INTEGRATION.md', 'CHANGELOG.md', ...guides.map(name => `docs/${name}`)];
}

export function outsideFences(markdown, transform) {
  let fence = null;
  return markdown.split('\n').map(line => {
    const marker = /^ {0,3}(`{3,}|~{3,})/u.exec(line)?.[1];
    if (marker) {
      if (!fence) fence = marker;
      else if (marker[0] === fence[0] && marker.length >= fence.length) fence = null;
      return line;
    }
    return fence ? line : transform(line);
  }).join('\n');
}

function absoluteLink(target, source) {
  if (/^(?:[a-z][a-z0-9+.-]*:|\/\/)/iu.test(target)) return target;
  if (target.startsWith('#')) return `${rawBase}${source}${target}`;
  return `${rawBase}${posix.normalize(posix.join(posix.dirname(source), target))}`;
}

export async function renderAiContext() {
  const metadata = JSON.parse(await readFile(resolve(root, 'package.json'), 'utf8'));
  const sources = await documentationSources();
  const parts = [
    '# RelaySwarm full documentation context',
    `> Generated from maintained Markdown. Source package ${metadata.version}; release and deployment evidence is recorded in docs/STATUS.md.`,
    'Canonical repository: https://github.com/forgesworn/relayswarm. Main-branch documentation can correct released documentation. Historical spike evidence is indexed separately in llms.txt.',
    'Regenerate with `npm run docs:generate`; do not edit this file by hand.',
  ];
  for (const source of sources) {
    const markdown = await readFile(resolve(root, source), 'utf8');
    const linked = outsideFences(markdown, line => line.replace(
      /(!?\[[^\]\n]*\]\()([^\s)]+)(\))/gu,
      (_, prefix, target, suffix) => `${prefix}${absoluteLink(target, source)}${suffix}`,
    ));
    parts.push(`---\n\nSource: [${source}](${rawBase}${source})\n\n${linked.trimEnd()}`);
  }
  return `${parts.join('\n\n')}\n`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await writeFile(resolve(root, 'llms-full.txt'), await renderAiContext());
  console.log('Generated llms-full.txt from maintained documentation.');
}
